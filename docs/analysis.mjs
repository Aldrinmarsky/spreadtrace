export const COLUMNS = [
  'kind', 'time_msc', 'symbol', 'chart_price', 'bid', 'ask', 'last', 'deal_id',
  'side', 'entry', 'reason', 'price', 'stop', 'volume',
];

const EXIT_ENTRIES = new Set(['DEAL_ENTRY_OUT', 'DEAL_ENTRY_OUT_BY', 'DEAL_ENTRY_INOUT']);
export const MAX_BYTES = 24 * 1024 * 1024;

function splitRow(line) {
  if (!line.includes('"')) return line.split(',');
  const field = /(?:"((?:[^"]|"")*)"|([^",]*))(,|$)/y;
  const cells = [];
  do {
    const match = field.exec(line);
    if (!match) throw new Error('Malformed CSV field');
    cells.push(match[1]?.replaceAll('""', '"') ?? match[2]);
    if (!match[3]) break;
  } while (true);
  return cells;
}

function number(value, name, optional = false) {
  if (optional && value === '') return null;
  if (!/^[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:e[+-]?\d+)?$/i.test(value) ||
      !Number.isFinite(Number(value))) {
    throw new Error(`Invalid ${name}`);
  }
  return Number(value);
}

export function readCapture(csv) {
  const lines = csv.replace(/^\uFEFF/, '').split(/\r?\n/);
  if (lines.shift() !== COLUMNS.join(',')) {
    throw new Error('Choose a CSV generated by the SpreadTrace recorder.');
  }
  const quotes = [];
  const exits = [];
  const tickets = new Set();
  let captureSymbol;
  let chartPrice;
  for (const [index, line] of lines.entries()) {
    if (!line.trim()) continue;
    try {
      const cells = splitRow(line);
      if (cells.length !== COLUMNS.length) throw new Error('Incorrect column count');
      const [kind, timeText, symbol, mode, bid, ask, last, id, side, entry, reason, fill, stop, volume] = cells;
      const time = number(timeText, 'timestamp');
      if (!Number.isSafeInteger(time) || time <= 0 || time > 8.64e15) throw new Error('Invalid timestamp');
      if (!symbol || !['BID', 'LAST'].includes(mode)) throw new Error('Invalid symbol or chart price');
      captureSymbol ??= symbol;
      chartPrice ??= mode;
      if (symbol !== captureSymbol || mode !== chartPrice) throw new Error('Multiple symbols or chart modes');

      if (kind === 'quote') {
        quotes.push({ time, bid: number(bid, 'Bid', true), ask: number(ask, 'Ask', true),
          last: number(last, 'Last', true) });
      } else if (kind === 'deal') {
        if (!/^\d+$/.test(id) || !['DEAL_TYPE_BUY', 'DEAL_TYPE_SELL'].includes(side)) {
          throw new Error('Invalid deal ID or side');
        }
        const trade = { id, time, side: side === 'DEAL_TYPE_BUY' ? 'Buy' : 'Sell',
          entry, reason, fill: number(fill, 'fill'), stop: entry === 'DEAL_ENTRY_INOUT' ? null : number(stop, 'stop', true),
          volume: number(volume, 'volume') };
        if (EXIT_ENTRIES.has(entry) && !tickets.has(id)) {
          exits.push(trade);
          tickets.add(id);
        }
      } else {
        throw new Error('Unknown record type');
      }
    } catch (error) {
      throw new Error(`Line ${index + 2} · ${error.message}`);
    }
  }
  if (!captureSymbol) throw new Error('This capture has no records yet.');
  quotes.sort((a, b) => a.time - b.time);
  exits.sort((a, b) => b.time - a.time);
  return { symbol: captureSymbol, chartPrice, quotes, exits };
}

function lowerBound(rows, time) {
  let left = 0;
  let right = rows.length;
  while (left < right) {
    const mid = Math.floor((left + right) / 2);
    if (rows[mid].time < time) left = mid + 1;
    else right = mid;
  }
  return left;
}

export function quoteSpread(quote) {
  if (quote?.bid == null || quote.ask == null || quote.ask < quote.bid) return null;
  return quote.ask - quote.bid;
}

export function inspectExit(capture, exit, seconds, reference = 'auto') {
  const from = exit.time - seconds * 1000;
  const to = exit.time + seconds * 1000;
  const rows = capture.quotes;
  const quotes = rows.slice(lowerBound(rows, from), lowerBound(rows, to + 1));
  const atExit = lowerBound(quotes, exit.time);
  const afterExit = lowerBound(quotes, exit.time + 1);
  const before = quotes[atExit - 1];
  const after = quotes[afterExit];
  let peak = null;
  for (const quote of quotes) {
    const spread = quoteSpread(quote);
    if (spread !== null && (peak === null || spread > peak)) peak = spread;
  }
  const automaticSide = exit.side === 'Buy' ? 'ask' : 'bid';
  const side = reference === 'auto' ? (capture.chartPrice === 'LAST' ? 'last' : automaticSide) : reference;
  let state;
  let crossing;
  if (exit.reason !== 'DEAL_REASON_SL') {
    state = 'other';
  } else if (exit.entry !== 'DEAL_ENTRY_OUT' || exit.stop === null) {
    state = 'unavailable';
  } else {
    const candidateQuotes = quotes.slice(0, afterExit).filter((quote) => quote[side] !== null);
    crossing = candidateQuotes.find((quote) =>
      exit.side === 'Buy' ? quote[side] >= exit.stop : quote[side] <= exit.stop);
    if (crossing) state = crossing.time === exit.time ? 'same-time' : 'crossed';
    else state = candidateQuotes.length ? 'unseen' : 'missing';
  }
  return { from, to, quotes, before, after, peak, side, state, crossing,
    sameTimeCount: afterExit - atExit };
}

export function formatTime(time) {
  return new Date(time).toISOString().slice(11, 23);
}
